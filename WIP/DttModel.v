(* [ott_pi_noeta = tl ott_pi] is defined in WIP/DttPiNoEta.v rather than here.
   That file exists only to isolate a HINT-DATABASE hazard: Lang/OTT/Pi.v
   exports [ott_pi_entry : wf_lang_ext _ ott_pi] into [wf_lang_db], and that
   entry rests on [Interactive.todo].  With Pi.v imported, [compute_wf_lang]
   picks the entry up opportunistically and every language wf proof in the
   file comes out axiom-dirty -- even for languages that do not contain the
   eta rule (verified: [wf_lang (ott_nat ++ ott_base ++ subst_ott ++
   ott_info)] is dirty with Pi imported, clean without).  Requiring
   DttPiNoEta (which does not Export Pi) gives us the VALUE without the
   hint, and [ott_dtt_wf] below is then axiom-free. *)

Definition ott_dtt : lang := Eval vm_compute in
  (ott_pi_noeta ++ ott_nat ++ ott_base ++ subst_ott ++ ott_info).

(* 68 rules: 32 term_rule, 27 term_eq_rule, 9 sort_rule, 0 sort_eq_rule.
   The last figure is the single most consequential fact about this
   language: it has NO sort equations at all.  Sorts are indexed by TERMS
   ([ty G i], [exp G i A]) and all "type equality" of the object theory is
   term equality at the sort [ty].  Consequently the [csort_by] obligation of
   CutTModel_ok is VACUOUS, and [Ceq_sort] is generated by [csort_cong]
   alone -- but is still not [eq], because [Ceq_term] at [ty] is not [eq].

   PROVED, and axiom-free ([Print Assumptions] = "Closed under the global
   context").  This is the only real proof in the skeleton. *)
Lemma ott_dtt_wf : wf_lang ott_dtt.
Proof. compute_wf_lang. Qed.

