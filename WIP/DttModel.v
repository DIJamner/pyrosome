(* Index normal forms                                                   *)
(*                                                                      *)
(* [relevance] and [lvl] are rigid (no equations, two closed constructors *)
(* each).  [tlvl] has the two equations "next0" ([next L0 = iota L1]) and *)
(* "next1" ([next L1 = inf]); its normal forms are therefore exactly      *)
(* [iota L0], [iota L1], [inf] -- a THREE-element set.  [tyinfo] has one  *)
(* constructor, so its normal forms are the six [info r n].              *)
(*                                                                      *)
(* [ntlvl]/[ninfo] below are total normalizers on the index syntax; they  *)
(* are what [Ceq_term] uses at these sorts, so that index equality is     *)
(* DECIDED rather than carried.                                          *)
(* ------------------------------------------------------------------ *)

Inductive RelNf : term -> Prop :=
| relnf_rel : RelNf oRel
| relnf_irr : RelNf oIrr.

Inductive LvlNf : term -> Prop :=
| lvlnf_L0 : LvlNf oL0
| lvlnf_L1 : LvlNf oL1.

Inductive TlvlNf : term -> Prop :=
| tlvlnf_iota : forall l, LvlNf l -> TlvlNf (oIota l)
| tlvlnf_inf : TlvlNf oInf.

Inductive InfoNf : term -> Prop :=
| infonf : forall r n, RelNf r -> TlvlNf n -> InfoNf (oInfo r n).

(* The normalizer.  [next L0 = iota L1] and [next L1 = inf] are the only
   tlvl equations, so this is a one-step rewrite. *)
Definition ntlvl (n : term) : term :=
  match n with
  | con "next" [l] =>
      match l with
      | con "L0" [] => oIota oL1
      | con "L1" [] => oInf
      | _ => n
      end
  | _ => n
  end.

Definition ninfo (i : term) : term :=
  match i with
  | con "info" [n; r] => oInfo r (ntlvl n)
  | _ => i
  end.

Lemma ntlvl_nf n : TlvlNf (ntlvl n) \/ ntlvl n = n.
Admitted.

Lemma ninfo_idem i : ninfo (ninfo i) = ninfo i.
Admitted.

(* The soundness/completeness of the index normalizer against the theory.
   Soundness is by the two equations; completeness (the converse) is one of
   the RIGIDITY facts, and is proved by an auxiliary CutTModel (see
   WIP/DttRigidity.v in the design doc's Layer 0.5), not here. *)
Lemma ntlvl_sound n
  : wf_term ott_dtt [] n sTlvl -> eq_term ott_dtt [] sTlvl n (ntlvl n).
Admitted.

Lemma ninfo_sound i
  : wf_term ott_dtt [] i sInfo -> eq_term ott_dtt [] sInfo i (ninfo i).
Admitted.

Lemma ninfo_complete i1 i2
  : wf_term ott_dtt [] i1 sInfo ->
    wf_term ott_dtt [] i2 sInfo ->
    eq_term ott_dtt [] sInfo i1 i2 ->
    ninfo i1 = ninfo i2.
Admitted.
