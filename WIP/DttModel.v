(* =====================================================================
   DTT NORMALIZATION, LAYER 0: the target language and its index syntax.

   This is the analogue of Gluing/Stlc/Syntax.v for the dependent theory of
   src/Pyrosome/Lang/OTT/.  It is a SKELETON: every Definition/Inductive
   typechecks; lemma statements are Admitted.  Nothing here is imported by
   src/, and WIP/ is not part of the build.

   TARGET LANGUAGE.  [ott_dtt] is
       ott_pi_noeta ++ ott_nat ++ ott_base ++ subst_ott ++ ott_info
   i.e. Lang/OTT's Tarski-universe core (U/El, two levels, relevance tags),
   the parameterized substitution calculus, Nat/zero/suc/Empty/Emptyrec, and
   dependent Pi (relevant + irrelevant) with beta and the substitution
   commutations -- MINUS the "Pi_rel eta" rule.

   Why minus eta: Lang/OTT/Pi.v adds that rule with [push_rule_todo], which
   discharges its wf obligation with Tools/Interactive.v's [Axiom todo].  So
   [ott_pi] is axiom-dirty, and [tl ott_pi] is the largest axiom-free prefix.
   Dropping eta is also what keeps reification untyped (see the design doc).

   Why Nat is in: exactly the [unit_lang] situation of the STLC proof.  The
   only closed codes of [U r l] are Nat, Empty and Pi-of-codes; without a
   base code the universe is empty, [El A] is uninhabited for every A, and
   the normalization statement is vacuous.  Nat is the base case.

   SHAPES.  Every constructor's argument order below was read off the
   COMPILED language (rule contexts are stored most-recent-first and [con]'s
   argument list follows that order), not off the surface notation.  They were
   verified by [Eval vm_compute] on [named_map summ ott_core]; see the design
   doc for the dump.  Note in particular:
     - [snoc]'s con list is [v;g;A;i;G';G]  (v BEFORE g, unlike the STLC
       language where it was [v;A;g;G';G]);
     - [hd], [wkn], [id], [forget], [emp] carry their index arguments in the
       con list even though their [args] fields are empty;
     - [Empty] and [Pi_irr] are elaborated at info [rel (iota L1)], while
       [Nat] is elaborated at info [rel (next L0)] -- the two are equal only
       via the "next0" equation.  This is the smallest witness that
       [Ceq_sort] cannot be [eq].
   ===================================================================== *)

Notation term := (@term string).
