(* ------------------------------------------------------------------ *)
(* FUNCTIONALITY                                                        *)
(*                                                                      *)
(* With syntactic guards this is an ordinary induction: the six clauses  *)
(* are pairwise disjoint by the head symbol of the type ([U] vs [El],    *)
(* and within [El] the head of the code: [Nat], [Empty], [Pi_rel],       *)
(* [Pi_irr], neutral).  Contrast the eq_term-guarded design, where the   *)
(* corresponding statement would be [RTy G i A1 P1 -> RTy G i A2 P2 ->   *)
(* eqt A1 A2 -> ...], which is NOT provable without non-confusion of     *)
(* canonical codes -- a consequence of normalization, not an input.      *)
(* ------------------------------------------------------------------ *)

Lemma RTy_fun G i A P1 P2
  : RTy G i A P1 -> RTy G i A P2 -> forall e, P1 e <-> P2 e.
Admitted.

(* transfer along a type equation: free, by definition of [RTmN] *)
Lemma RTmN_ty_eq G i A A' e
  : RTmN G i A e -> eqt (sTy G i) A A' -> RTmN G i A' e.
Admitted.

Lemma RTyN_ty_eq G i A A' : RTyN G i A -> eqt (sTy G i) A A' -> RTyN G i A'.
Admitted.

(* invariance under provable equality of the TERM -- free from the [HasNf]
   conjunct that every clause carries *)
Lemma RTm_eq G i A e e'
  : RTm G i A e -> eqt (sExp G i A) e e' -> RTm G i A e'.
Admitted.

Lemma RTmN_eq G i A e e'
  : RTmN G i A e -> eqt (sExp G i A) e e' -> RTmN G i A e'.
Admitted.

(* ------------------------------------------------------------------ *)
(* Escape and reflect                                                   *)
(* ------------------------------------------------------------------ *)

Lemma RTy_wf G i A P : RTy G i A P -> wft A (sTy G i).
Admitted.

Lemma RTm_wf G i A e : RTm G i A e -> wft e (sExp G i A).
Admitted.

(* ESCAPE: a reducible term at a NORMAL type has a normal form.  This is
   what the top-level theorem consumes, and it needs no case analysis --
   every clause carries [HasNf] (for [rty_ne]/[rty_empty] via [HasNe], for
   [rty_U] via [HasNfCode] and [nfet_code]). *)
Lemma RTm_escape G i A e
  : RTm G i A e -> TyOk G i A -> HasNf G i A e.
Admitted.

(* REFLECT: a neutral of a reducible type is reducible.  Uniform over the
   clauses again: every candidate admits its neutrals. *)
Lemma RTm_reflect G i A e
  : RTyEx G i A -> HasNe G i A e -> EnvOk G -> RTm G i A e.
Admitted.

(* the special case Layer 3 needs: object-level variables are reducible *)
Lemma RTm_var G i A x
  : VarT G i A x -> EnvOk G -> TyOk G i A -> RTm G i A x.
Admitted.

(* ------------------------------------------------------------------ *)
(* Every normal type is reducible                                       *)
(*                                                                      *)
(* This is the bridge that replaces the negative occurrence of [RTy] in  *)
(* the universe clause.  It is a plain induction on [NfCode]/[TyOk].     *)
(* ------------------------------------------------------------------ *)

Lemma RTyEx_of_NfCode G r e
  : NfCode G r e -> EnvOk G -> RTyEx G (iE r) (tEl G r e).
Admitted.

Lemma RTyEx_of_TyOk G i A : TyOk G i A -> RTyEx G i A.
Admitted.

(* ------------------------------------------------------------------ *)
(* Stability under weakening                                            *)
(* ------------------------------------------------------------------ *)

Lemma RTyN_wk G i A D w
  : RTyN G i A -> Wk D G w -> EnvOk D -> EnvOk G ->
    RTyN D i (oTySubst D G w i A).
Admitted.

Lemma RTmN_wk G i A e D w
  : RTmN G i A e -> RTyN G i A -> Wk D G w -> EnvOk D -> EnvOk G ->
    RTmN D i (oTySubst D G w i A) (oExpSubst D G w i A e).
Admitted.

