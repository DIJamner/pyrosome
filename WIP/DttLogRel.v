(* The Pi interface consumed by Layer 4                                 *)
(* ------------------------------------------------------------------ *)

(* Application of a reducible function to a reducible argument, at the
   identity weakening -- the form the [app_rel] congruence obligation
   consumes (compare Stlc/LogRel.v's [RV_apply]).

   NOTE how the syntactic-guard discipline pays off here.  The hypothesis
   is [RTm] at the SYNTACTIC Pi type, so [RTy_fun] plus inversion on the
   (unique) applicable clause hands back the Kripke property directly.  In
   the eq_term-guarded design this step would have required knowing that
   the Pi type is not convertible to [Nat] or to a neutral. *)
Lemma RTm_app_rel G rF F B f a
  : RTm G (iE oRel) (tEl G oRel (oPiRel G rF oL0 oL0 F B)) f ->
    RTm G (iE rF) (tEl G rF F) a ->
    EnvOk G -> NfCode G rF F -> NfCode (oExtC0 G rF F) oRel B ->
    RTmN G (iE oRel) (tCodAtR G rF F B G (oId G) a)
      (oAppRel G rF oL0 oL0 F B f a).
Admitted.

Lemma RTm_app_irr G rF F B f a
  : RTm G (iE oIrr) (tEl G oIrr (oPiIrr G rF oL0 F B)) f ->
    RTm G (iE rF) (tEl G rF F) a ->
    EnvOk G -> NfCode G rF F -> NfCode (oExtC0 G rF F) oIrr B ->
    RTmN G (iE oIrr) (tCodAtI G rF F B G (oId G) a)
      (oAppIrr G rF oL0 F B f a).
Admitted.

(* Introduction: a lambda whose body is reducible at every reducible
   argument is reducible.  This is where "Pi_rel beta" is used, and it is
   the ONLY place in the whole development where a beta step happens --
   everything else is discharged by the substitution equations of the
   theory itself. *)
Lemma RTm_lam_rel G rF F B t
  : EnvOk G -> NfCode G rF F -> NfCode (oExtC0 G rF F) oRel B ->
    (forall D w a, Wk D G w -> EnvOk D ->
        RTmN D (iE rF) (tDomAt G rF F D w) a ->
        RTmN D (iE oRel) (tCodAtR G rF F B D w a)
          (oExpSubst D (oExtC0 G rF F) (oSnocAt G rF F D w a) (iE oRel)
             (oEl (oExtC0 G rF F) oRel oL0 B) t)) ->
    RTm G (iE oRel) (tEl G oRel (oPiRel G rF oL0 oL0 F B))
      (oLamRel G rF oL0 oL0 F B t).
Admitted.

(* the same for the irrelevant Pi *)
Lemma RTm_lam_irr G rF F B t
  : EnvOk G -> NfCode G rF F -> NfCode (oExtC0 G rF F) oIrr B ->
    (forall D w a, Wk D G w -> EnvOk D ->
        RTmN D (iE rF) (tDomAt G rF F D w) a ->
        RTmN D (iE oIrr) (tCodAtI G rF F B D w a)
          (oExpSubst D (oExtC0 G rF F) (oSnocAt G rF F D w a) (iE oIrr)
             (oEl (oExtC0 G rF F) oIrr oL0 B) t)) ->
    RTm G (iE oIrr) (tEl G oIrr (oPiIrr G rF oL0 F B))
      (oLamIrr G rF oL0 F B t).
Admitted.
